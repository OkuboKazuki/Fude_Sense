#include "EvaluationResult.h"

// ---------------------------------------------------------------------------
// 一致率などの生の指標を 0〜100 の点数へ写像する。
//
// 毛筆フォントのグリフと筆で書いた字では太さの出方が違うので、
// 重なり率がそのまま 1.00 になることは原理的に無い。
// 生の一致率をそのまま100倍すると、丁寧に書いても 50 点台にしかならず
// 使う側の感覚と合わない。そこで「実際に到達しうる範囲」を 0〜100 へ
// 引き伸ばす。その範囲をどこに置くかがこの機能の肝で、
// しきい値は EvaluationScore.cpp の先頭に集約してある。
//
// ★ 現在のしきい値は暫定値。丁寧に書いた字とわざと崩した字で
//    妥当な点差がつくかを見て調整することを前提にしている。
// ---------------------------------------------------------------------------

class EvaluationScore {
public:
    // 比較結果の各マスに点数を入れ、総合点を求める。
    static void Apply(CompareResult& result);

    // 点数に対応する短い評語。詳細を畳んでいるときの手がかりにする。
    static const wchar_t* GradeLabel(double score);
};
